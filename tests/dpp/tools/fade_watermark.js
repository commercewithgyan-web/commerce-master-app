#!/usr/bin/env node
/**
 * Builds a pre-faded copy of the DPP watermark PNG so the PDF no longer depends
 * on CSS `opacity` (which the Drive HTML->PDF converter may ignore).
 * Reads getDppWatermarkBase64_() from backend/dpp_brand_assets.gs and writes
 * backend/dpp_watermark_faded.gs with getDppWatermarkFadedBase64_().
 *
 *   node tests/dpp/tools/fade_watermark.js [strength=0.07] [size=420]
 */
'use strict';
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const STRENGTH = parseFloat(process.argv[2] || '0.07');
const OUT_SIZE = parseInt(process.argv[3] || '420', 10);
const BACKEND = path.join(__dirname, '..', '..', '..', 'backend');
const src = fs.readFileSync(path.join(BACKEND, 'dpp_brand_assets.gs'), 'utf8');
const m = src.match(/function getDppWatermarkBase64_\(\)\s*\{\s*return '([^']+)'/);
if (!m) throw new Error('watermark base64 not found');
const png = Buffer.from(m[1], 'base64');

// --- decode PNG (8-bit RGB / RGBA, non-interlaced) ---
let pos = 8, width, height, colorType, idat = [];
while (pos < png.length) {
  const len = png.readUInt32BE(pos), type = png.toString('ascii', pos + 4, pos + 8);
  const data = png.slice(pos + 8, pos + 8 + len);
  if (type === 'IHDR') {
    width = data.readUInt32BE(0); height = data.readUInt32BE(4);
    if (data[8] !== 8 || data[12] !== 0) throw new Error('only 8-bit non-interlaced PNG supported');
    colorType = data[9];
  } else if (type === 'IDAT') idat.push(data);
  else if (type === 'IEND') break;
  pos += 12 + len;
}
const bpp = colorType === 6 ? 4 : colorType === 2 ? 3 : 0;
if (!bpp) throw new Error('unsupported color type ' + colorType);
const raw = zlib.inflateSync(Buffer.concat(idat));
const stride = width * bpp;
const px = Buffer.alloc(height * stride);
for (let y = 0; y < height; y++) {
  const f = raw[y * (stride + 1)];
  const line = raw.slice(y * (stride + 1) + 1, (y + 1) * (stride + 1));
  for (let x = 0; x < stride; x++) {
    const a = x >= bpp ? px[y * stride + x - bpp] : 0;
    const b = y > 0 ? px[(y - 1) * stride + x] : 0;
    const c = (x >= bpp && y > 0) ? px[(y - 1) * stride + x - bpp] : 0;
    let v = line[x];
    if (f === 1) v += a;
    else if (f === 2) v += b;
    else if (f === 3) v += (a + b) >> 1;
    else if (f === 4) { const p = a + b - c, pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c); v += (pa <= pb && pa <= pc) ? a : (pb <= pc ? b : c); }
    px[y * stride + x] = v & 255;
  }
}

// --- box-downscale + blend toward white ---
const out = Buffer.alloc(OUT_SIZE * OUT_SIZE * 3);
for (let oy = 0; oy < OUT_SIZE; oy++) {
  for (let ox = 0; ox < OUT_SIZE; ox++) {
    const x0 = Math.floor(ox * width / OUT_SIZE), x1 = Math.max(x0 + 1, Math.floor((ox + 1) * width / OUT_SIZE));
    const y0 = Math.floor(oy * height / OUT_SIZE), y1 = Math.max(y0 + 1, Math.floor((oy + 1) * height / OUT_SIZE));
    const acc = [0, 0, 0]; let n = 0;
    for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) {
      const i = y * stride + x * bpp;
      const alpha = bpp === 4 ? px[i + 3] / 255 : 1;
      for (let k = 0; k < 3; k++) acc[k] += 255 - (255 - px[i + k]) * alpha;
      n++;
    }
    for (let k = 0; k < 3; k++) {
      const c = acc[k] / n;
      out[(oy * OUT_SIZE + ox) * 3 + k] = Math.round(255 - (255 - c) * STRENGTH);
    }
  }
}

// --- encode PNG (RGB, filter 0) ---
const rows = Buffer.alloc(OUT_SIZE * (OUT_SIZE * 3 + 1));
for (let y = 0; y < OUT_SIZE; y++) out.copy(rows, y * (OUT_SIZE * 3 + 1) + 1, y * OUT_SIZE * 3, (y + 1) * OUT_SIZE * 3);
const crcTable = Array.from({ length: 256 }, (_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c >>> 0; });
const crc = (buf) => { let c = 0xffffffff; for (const b of buf) c = crcTable[(c ^ b) & 255] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
const chunk = (type, data) => {
  const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const c = Buffer.alloc(4); c.writeUInt32BE(crc(td));
  return Buffer.concat([len, td, c]);
};
const ihdr = Buffer.alloc(13);
ihdr.writeUInt32BE(OUT_SIZE, 0); ihdr.writeUInt32BE(OUT_SIZE, 4); ihdr[8] = 8; ihdr[9] = 2;
const outPng = Buffer.concat([
  Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
  chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(rows, { level: 9 })), chunk('IEND', Buffer.alloc(0))
]);

const b64 = outPng.toString('base64');
const gs = '/**\n * Pre-faded DPP watermark (generated by tests/dpp/tools/fade_watermark.js).\n' +
  ' * Strength ' + STRENGTH + ', ' + OUT_SIZE + 'x' + OUT_SIZE + ' px. The fade is baked into the pixels,\n' +
  ' * so the PDF does not rely on CSS opacity. Regenerate instead of editing.\n */\n' +
  'function getDppWatermarkFadedBase64_() {\n  return \'' + b64 + '\';\n}\n';
fs.writeFileSync(path.join(BACKEND, 'dpp_watermark_faded.gs'), gs);
// preview: write outPng to a scratch path if you want to look at it
console.log('wrote dpp_watermark_faded.gs (' + b64.length + ' base64 chars, was ' + m[1].length + ')');
